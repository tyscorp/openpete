#!/usr/bin/env python3
"""Emit the PSYQ abort-on-call stubs that no thunk defines, and each game's
address table for them.

Usage:
    filter_psyq_stubs.py union OUTPUT_C --stubs STUBS_C... --thunks SOURCE...
    filter_psyq_stubs.py table OUTPUT_C --tag TAG --stubs STUBS_C --thunks SOURCE...

STUBS_C is a game's generated psyq_stubs.c (tools/gen_psyq_stubs.py): one
`OPENPETE_WEAK void psyq_NAME(CPUState* cpu) { psyq_stub_hit(..., ADDR, cpu); }`
line per manifest symbol. SOURCE... are the shared thunk layer's
translation units; a name a source defines as
`void psyq_NAME(CPUState* ...) {` is a thunk and gets no stub.

union: the union of every given game's stub names minus the thunks, one
strong definition each, compiled once and linked into every executable.
A stub body names only its symbol; psyq_stub_hit looks the running game's
address up in that game's table. A thunk the scan misses is a
multiple-definition error at link time, and a name it matches that no
translation unit compiles is an undefined reference, on ELF and PE alike.

table: one game's stub names minus the thunks with that game's addresses,
as `const psyq_stub_table_t <TAG>_psyq_stub_table`
(games/common/psyq/psyq_game_hooks.h), the game's PSYQ descriptor's `stubs`.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

STUB_RE = re.compile(
    r'^OPENPETE_WEAK void (psyq_\w+)\(CPUState\* cpu\) \{ '
    r'psyq_stub_hit\("psyq_\w+", (0x[0-9A-Fa-f]+)u, cpu\); \}\s*$')
DEF_RE = re.compile(r"\bvoid\s+(psyq_\w+)\s*\(\s*CPUState\s*\*\s*\w*\s*\)(?:\s*OP_\w+\(\w*\))*\s*\{")

UNION_HEADER = """\
/* Generated by tools/filter_psyq_stubs.py -- do not edit.
 *
 * The abort-on-call stubs for the PSYQ symbols of every built game's
 * manifest ({games}) that no thunk defines, as strong definitions;
 * {n_drop} names a thunk defines are omitted. psyq_stub_hit
 * (psyq_stub_runtime.c) reports the running game's address for the name. No
 * libc header is included, since PSYQ exports stdlib names (printf, strlen,
 * rand, ...) whose stubs would collide with libc's prototypes.
 */

#include "psx_runtime_internal.h"

extern void psyq_stub_hit(const char* name, CPUState* cpu);

"""

TABLE_HEADER = """\
/* Generated by tools/filter_psyq_stubs.py from {stubs} -- do not edit.
 *
 * This game's guest address for each PSYQ abort-on-call stub, sorted by
 * name; {n_drop} names a thunk defines are omitted.
 */

#include "psyq/psyq_game_hooks.h"

"""


def defined_names(sources: list[str]) -> set[str]:
    """Return the psyq_ names the sources define with the thunk signature."""
    names: set[str] = set()
    for src in sources:
        p = Path(src)
        if src.endswith((".c", ".cpp")) and p.is_file():
            names.update(DEF_RE.findall(p.read_text(errors="replace")))
    return names


def parse_stubs(path: Path) -> dict[str, int]:
    """Return {stub name: guest address} for every stub line of a psyq_stubs.c."""
    stubs: dict[str, int] = {}
    for line in path.read_text().splitlines():
        m = STUB_RE.match(line)
        if m:
            stubs.setdefault(m.group(1), int(m.group(2), 16))
    if not stubs:
        sys.exit(f"filter_psyq_stubs: no stub lines in {path}")
    return stubs


def write_if_changed(output: Path, text: str) -> None:
    """Write text to output unless it already holds exactly that text."""
    if not output.exists() or output.read_text() != text:
        output.write_text(text)


def main() -> int:
    ap = argparse.ArgumentParser(usage=__doc__)
    ap.add_argument("mode", choices=("union", "table"))
    ap.add_argument("output")
    ap.add_argument("--tag")
    ap.add_argument("--stubs", nargs="+", required=True)
    ap.add_argument("--thunks", nargs="+", required=True)
    a = ap.parse_args()

    thunked = defined_names(a.thunks)
    output = Path(a.output)
    if a.mode == "union":
        names: set[str] = set()
        for s in a.stubs:
            names.update(parse_stubs(Path(s)))
        kept = sorted(names - thunked)
        games = ", ".join(Path(s).parent.parent.name for s in a.stubs)
        text = UNION_HEADER.format(games=games, n_drop=len(names) - len(kept))
        text += "".join(f'void {n}(CPUState* cpu) {{ psyq_stub_hit("{n}", cpu); }}\n'
                        for n in kept)
        write_if_changed(output, text)
        print(f"filter_psyq_stubs: union of {len(a.stubs)} games: {len(kept)} "
              f"stubs kept, {len(names) - len(kept)} defined by thunks")
        return 0

    if not a.tag or len(a.stubs) != 1:
        ap.error("table takes --tag and one --stubs file")
    stubs = parse_stubs(Path(a.stubs[0]))
    kept = sorted(n for n in stubs if n not in thunked)
    text = TABLE_HEADER.format(stubs=Path(a.stubs[0]).name,
                               n_drop=len(stubs) - len(kept))
    if kept:
        text += "static const psyq_stub_addr_t k_entries[] = {\n"
        text += "".join(f'    {{ "{n}", 0x{stubs[n]:08X}u }},\n' for n in kept)
        text += ("};\n\n"
                 f"const psyq_stub_table_t {a.tag}_psyq_stub_table = {{\n"
                 "    k_entries, sizeof k_entries / sizeof k_entries[0],\n"
                 "};\n")
    else:
        text += f"const psyq_stub_table_t {a.tag}_psyq_stub_table = {{ NULL, 0 }};\n"
    write_if_changed(output, text)
    print(f"filter_psyq_stubs: {a.tag}: {len(kept)} stub addresses, "
          f"{len(stubs) - len(kept)} defined by thunks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
