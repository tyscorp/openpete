#!/usr/bin/env python3
"""Fence: each game's generated C was produced by the current recompiler.

scripts/regen-recomp.sh regenerates one game per call and translates with
the binary at third_party/psxrecomp/build/PSXRecomp. A change to the
recompiler's source therefore leaves every game it was not re-run for, and
every game regenerated by a binary not rebuilt from that source, compiling
generated C the current recompiler would not emit.

The recompiler's identity is a SHA-256 over its source files (every file
under third_party/psxrecomp/recompiler/ with a source or build extension,
outside dot-directories and the vendored documentation), read from the
working tree, so an uncommitted edit changes it too and no git is needed.
regen-recomp.sh removes games/<game>/generated/psxrecomp.id when it starts
and writes the identity there when it finishes, after building the
recompiler from that source; a failed regen leaves no stamp. The build
runs `check` for every configured game and refuses on a missing or
different stamp, naming the regen command; for a game whose generated
directory is a link (a worktree reading the main checkout's tree) it says
never to regenerate there instead.

Escape: OPENPETE_RECOMP_STAMP_SKIP="<reason>" makes `check` print the
reason and pass.

Run:  python3 scripts/fences/recomp_stamp.py id [repo root]
      python3 scripts/fences/recomp_stamp.py write <game> [repo root]
      python3 scripts/fences/recomp_stamp.py check <game>... [--root <repo root>]
Exit: 0 clean, 67 a stamp is missing or differs, 64 the recompiler source
      is missing or a game has no generated directory.
"""
import hashlib
import os
import sys

SRC_REL = os.path.join("third_party", "psxrecomp", "recompiler")
EXTS = (".c", ".cc", ".cpp", ".h", ".hh", ".hpp", ".inc", ".def", ".txt", ".cmake", ".py", ".toml")
SKIP_DIRS = {"doc", "docs", "examples", "tests", "build"}
STAMP = "psxrecomp.id"


def recomp_id(root):
    """@brief Return the SHA-256 of the recompiler source tree, or None when it is missing."""
    src = os.path.join(root, SRC_REL)
    if not os.path.isdir(src):
        return None
    h = hashlib.sha256()
    files = 0
    for dirpath, dirnames, filenames in os.walk(src):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and d not in SKIP_DIRS)
        for name in sorted(filenames):
            if not name.endswith(EXTS) and name != "CMakeLists.txt":
                continue
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, src).replace(os.sep, "/")
            with open(path, "rb") as f:
                data = f.read()
            h.update(rel.encode() + b"\0" + str(len(data)).encode() + b"\0" + data)
            files += 1
    return None if files == 0 else h.hexdigest()


def stamp_path(root, game):
    """@brief Return the stamp file path of a game's generated directory."""
    return os.path.join(root, "games", game, "generated", STAMP)


def main(argv):
    """@brief Dispatch the id, write and check subcommands; return the exit code."""
    if len(argv) < 2 or argv[1] not in ("id", "write", "check"):
        print(__doc__, file=sys.stderr)
        return 64
    cmd = argv[1]
    args = argv[2:]
    root = os.getcwd()
    if "--root" in args:
        i = args.index("--root")
        root = args[i + 1]
        del args[i:i + 2]
    elif cmd == "id" and args:
        root = args.pop(0)
    elif cmd == "write" and len(args) == 2:
        root = args.pop(1)
    cur = recomp_id(root)
    if cur is None:
        print(f"recomp-stamp: no recompiler source under {os.path.join(root, SRC_REL)}", file=sys.stderr)
        return 64
    if cmd == "id":
        print(cur)
        return 0
    if cmd == "write":
        if len(args) != 1:
            print("recomp-stamp: write takes one game", file=sys.stderr)
            return 64
        gen = os.path.dirname(stamp_path(root, args[0]))
        if not os.path.isdir(gen):
            print(f"recomp-stamp: {gen} is not a directory", file=sys.stderr)
            return 64
        tmp = stamp_path(root, args[0]) + ".tmp"
        with open(tmp, "w") as f:
            f.write(cur + "\n")
        os.replace(tmp, stamp_path(root, args[0]))
        print(f"recomp-stamp: {args[0]} stamped {cur[:12]}")
        return 0
    skip = os.environ.get("OPENPETE_RECOMP_STAMP_SKIP", "")
    if skip:
        print(f"recomp-stamp: SKIPPED by OPENPETE_RECOMP_STAMP_SKIP: {skip}")
        return 0
    if not args:
        print("recomp-stamp: check names no game", file=sys.stderr)
        return 64
    bad = []
    for game in args:
        p = stamp_path(root, game)
        if not os.path.isdir(os.path.dirname(p)):
            print(f"recomp-stamp: {game}: no generated directory {os.path.dirname(p)}", file=sys.stderr)
            return 64
        try:
            with open(p) as f:
                got = f.read().strip()
        except FileNotFoundError:
            got = ""
        if got != cur:
            state = "no stamp (never stamped, or the last regen failed)" if not got else f"stamped {got[:12]}"
            bad.append(f"  {game}: {state}; recompiler source is {cur[:12]}")
    if bad:
        print("recomp-stamp: generated C does not come from the current recompiler:", file=sys.stderr)
        for line in bad:
            print(line, file=sys.stderr)
        stale = [g for g in args if any(l.startswith(f"  {g}:") for l in bad)]
        linked = [g for g in stale if os.path.islink(os.path.dirname(stamp_path(root, g)))]
        if linked:
            # A worktree's generated tree is the main checkout's: a regen here
            # writes it (scripts/lib/regen_guard.py refuses one).
            for g in linked:
                print(f"  {g}: games/{g}/generated is a link to "
                      f"{os.path.realpath(os.path.dirname(stamp_path(root, g)))}", file=sys.stderr)
            print("  never regenerate in this checkout: test only commits whose stamp check passes "
                  "here. Regeneration belongs to the main checkout, or to a worktree made with "
                  "`worktree-setup.sh <name> --no-links`.", file=sys.stderr)
            stale = [g for g in stale if g not in linked]
        if stale:
            games = " ".join(stale)
            print(f"  regenerate: for g in {games}; do GAME=$g bash scripts/regen-recomp.sh || break; done",
                  file=sys.stderr)
        return 67
    print(f"recomp-stamp: {len(args)} game(s) match recompiler {cur[:12]}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
